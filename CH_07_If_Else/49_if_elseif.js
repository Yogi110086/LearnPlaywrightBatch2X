let score = 100;
if (score >= 90) {
    console.log("A Grade");
}
else if (score >= 80) {
    console.log("B Grade");
}

else if (score >= 70) {
    console.log("C Grade");
}
else if (score >= 60) {
    console.log("D Grade");
}
else if (score >= 50) {
    console.log("Fail");
    console.log("Please Re-attempt the test");
}